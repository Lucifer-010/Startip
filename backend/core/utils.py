import base64
import html
import re
from stellar_sdk import Keypair
from stellar_sdk.exceptions import SdkError, Ed25519PublicKeyInvalidError
from rest_framework.views import exception_handler
from rest_framework.response import Response
from rest_framework import status

def is_valid_stellar_address(address: str) -> bool:
    """
    Validates whether the string is a valid Stellar Public Key (G...).
    """
    if not address or not isinstance(address, str):
        return False
    if not address.startswith('G') or len(address) != 56:
        return False
    try:
        Keypair.from_public_key(address)
        return True
    except (SdkError, Ed25519PublicKeyInvalidError, Exception):
        return False


def verify_stellar_signature(wallet_address: str, message: str, signature_encoded: str) -> bool:
    """
    Verifies an Ed25519 signature generated by a Stellar wallet.
    Accepts signature as hex or base64.
    """
    if not is_valid_stellar_address(wallet_address):
        return False
    try:
        # Try hex decode first
        try:
            signature_bytes = bytes.fromhex(signature_encoded.strip())
        except ValueError:
            signature_bytes = base64.b64decode(signature_encoded.strip())

        keypair = Keypair.from_public_key(wallet_address)
        message_bytes = message.encode('utf-8')
        keypair.verify(message_bytes, signature_bytes)
        return True
    except Exception:
        return False


def sanitize_message(raw_text: str, max_length: int = 280) -> str:
    """
    Sanitizes supporter message to prevent XSS and injection attacks.
    Limits length to prevent UI overflow.
    """
    if not raw_text:
        return ""
    # Strip HTML tags
    clean = re.sub(r'<[^>]*?>', '', str(raw_text))
    # Escape HTML entities
    clean = html.escape(clean)
    # Normalize whitespace
    clean = ' '.join(clean.split())
    return clean[:max_length]


def custom_exception_handler(exc, context):
    """
    Consistent JSON error payload across all endpoints.
    """
    response = exception_handler(exc, context)
    if response is not None:
        custom_data = {
            'success': False,
            'status_code': response.status_code,
            'error': {
                'type': exc.__class__.__name__,
                'detail': response.data
            }
        }
        response.data = custom_data
    return response
